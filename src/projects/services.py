"""Project drafting, submission, tags, answers and image uploads.

Every function here is a participant write path, so **every one of them calls the deadline guard
first and the permission guard second**, before any transaction opens. See `core/guards.py` for why
that ordering is what makes the audit trail survive a refusal, and `teams/services.py` for the same
shape applied to team formation.

Three rules in this module are easy to break by accident and are therefore stated here:

1. **Every public function guards itself.** `set_tags`, `save_answers`, `add_image`,
   `remove_image` and `set_thumbnail` are not internal helpers that trust `update_project` to
   have checked -- each one is reachable on its own from a view, and a public write that assumes
   its caller guarded is one refactor away from being an unguarded write. `update_project` calls
   the private `_write_*` helpers after its own guards have passed.

2. **The clock is read once per request.** Each entry point takes `now = clock.now()` at the top
   and passes that same instant to the guard and to `submitted_at`. Two reads leave a window in
   which a submission is admitted by the guard and then stamped with a time after the deadline.

3. **The one-active-project rule is enforced by the database.** `create_project` pre-checks and
   raises `ProjectExists`, but the pre-check is a courtesy for the error message; the partial
   unique index `project_one_active_per_team_per_event` is the authority, and the `IntegrityError`
   it raises under a race is mapped to the same 409. Neither path may produce a 500.
"""

