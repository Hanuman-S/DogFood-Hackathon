def save_answers(*, actor: User, project: Project, answers: dict, request=None) -> None:
    """Store answers to the event's custom questions. Public write path, so it guards itself."""
    now = clock.now()
    guard_submissions_open(
        project.event,
        actor=actor,
        action="save_answers",
        target=project,
        request=request,
        now=now,
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="save_answers",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can answer its questions.",
    )

    with transaction.atomic():
        _write_answers(project, answers)

    audit.record(
        AuditAction.PROJECT_UPDATED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"fields": ["answers"]},
        request=request,
    )


def _write_answers(project: Project, answers: dict) -> None:
    """Validate and upsert `{question_id: value}`. No guards -- callers have run them."""
    if not answers:
        return

    questions = {
        question.pk: question
        for question in CustomQuestion.objects.filter(event_id=project.event_id)
    }

    for raw_id, raw_value in answers.items():
        try:
            question = questions[int(raw_id)]
        except (KeyError, TypeError, ValueError):
            # Includes a question belonging to another event: from here it simply does not exist.
            raise ValidationFailed("That question is not part of this event.") from None

        value = _clean_answer(question, raw_value)
        CustomAnswer.objects.update_or_create(
            project=project, question=question, defaults={"value": value}
        )


def _clean_answer(question: CustomQuestion, raw) -> str:
    """One text column serves every question kind, so the kind is validated here."""
    if question.kind == QuestionKind.BOOLEAN:
        if isinstance(raw, bool):
            return "true" if raw else "false"
        value = str(raw or "").strip().lower()
        if value in ("true", "yes", "on", "1"):
            return "true"
        if value in ("", "false", "no", "off", "0"):
            return "false"
        raise ValidationFailed(f"“{question.prompt}” takes yes or no.")

    value = str(raw or "").strip()

    if question.kind == QuestionKind.CHOICE:
        if value and value not in [str(choice) for choice in (question.choices or [])]:
            raise ValidationFailed(f"“{value}” is not one of the options for that question.")
        return value

    if question.kind == QuestionKind.URL and value:
        try:
            validate_web_url(value)
        except DjangoValidationError as exc:
            raise ValidationFailed(f"“{question.prompt}”: {exc.messages[0]}") from exc

    if question.kind == QuestionKind.SHORT_TEXT and len(value) > 300:
        raise ValidationFailed(f"“{question.prompt}” takes at most 300 characters.")

    return value


