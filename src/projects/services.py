def normalize_tag(raw: str) -> str:
    """Lowercase, trim, collapse internal whitespace.

    So `React`, ` react ` and `REACT` are one tag rather than three near-duplicates in the
    gallery's filter list. Called before the `Tag` row is looked up, never after.
    """
    return re.sub(r"\s+", " ", (raw or "").strip().lower())


def parse_tags(raw) -> list[str]:
    """Accept either a comma-separated string (the form) or a list (the API), and normalize."""
    if raw is None:
        return []
    values = raw.split(",") if isinstance(raw, str) else list(raw)

    seen: list[str] = []
    for value in values:
        tag = normalize_tag(str(value))
        if tag and tag not in seen:
            seen.append(tag)
    return seen


def render_markdown(text: str) -> str:
    """Render a project description to HTML that is safe to put in a page.

    Two stages, because neither alone is enough: `markdown-it-py` with `html=False` refuses to
    pass raw HTML through, and `nh3` (Rust ammonia) then enforces an allow-list on what the
    renderer itself produced. Links come back with `rel="noopener noreferrer nofollow"` -- the
    first two so a linked page cannot reach back through `window.opener`, `nofollow` because a
    public gallery anyone can post links to is otherwise an SEO donation box.
    """
    import nh3
    from markdown_it import MarkdownIt

    if not (text or "").strip():
        return ""

    rendered = MarkdownIt("commonmark", {"html": False, "linkify": False}).render(text)
    return nh3.clean(
        rendered,
        tags=MARKDOWN_ALLOWED_TAGS,
        attributes=MARKDOWN_ALLOWED_ATTRIBUTES,
        url_schemes=MARKDOWN_URL_SCHEMES,
        link_rel="noopener noreferrer nofollow",
    )


