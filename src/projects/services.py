# No count limit is specified in the brief. One is imposed anyway: tags feed the gallery's filter
# list and the search vector's weight-B term, and a project carrying two hundred of them would
# dominate both. Ten is more than any real project needs.
MAX_PROJECT_TAGS = 10

TAG_MAX_LENGTH = 60

# Pillow's own default ceiling is ~89 megapixels. Lowered here because a decompression bomb -- a
# few kilobytes on the wire that decode to hundreds of megabytes of pixels -- is the cheapest
# denial of service against an upload endpoint, and no hackathon screenshot needs 40 million
# pixels. Set at import time so it applies to every open in this process, including the probe.
Image.MAX_IMAGE_PIXELS = 40_000_000

# The file extension and Content-Type each verified format is stored and served as. The stored
# name is generated by this module, so the extension is a fact about the decoded image rather
# than anything the uploader claimed.
FORMAT_EXTENSIONS = {"JPEG": "jpg", "PNG": "png", "WEBP": "webp"}
FORMAT_CONTENT_TYPES = {"JPEG": "image/jpeg", "PNG": "image/png", "WEBP": "image/webp"}

# The tags markdown may produce. No `img`: an image in a description would be a remote URL
# fetched by the viewer's browser at render time, which breaks the portal's "renders with the
# network off" rule and leaks every reader's IP to whatever host the author chose. Descriptions
# get prose, lists, code and links; screenshots go through the upload path, which is verified.
MARKDOWN_ALLOWED_TAGS = {
    "p", "br", "hr", "em", "strong", "del", "code", "pre", "blockquote",
    "h1", "h2", "h3", "h4", "h5", "h6", "ul", "ol", "li", "a",
    "table", "thead", "tbody", "tr", "th", "td",
}
MARKDOWN_ALLOWED_ATTRIBUTES = {"a": {"href", "title"}}
MARKDOWN_URL_SCHEMES = {"http", "https", "mailto"}


class ProjectExists(ConflictError):
    """The team already has an active project for this event."""

    code = "project_exists"


