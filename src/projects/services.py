_UNSET = object()

# Editable content fields, in the order the edit form shows them.
CONTENT_FIELDS = (
    "name",
    "tagline",
    "description",
    "track",
    "repo_url",
    "demo_video_url",
    "live_url",
)


def _clean_url_fields(project: Project) -> None:
    """http/https only, on every URL a viewer will see rendered as a link."""
    for field in ("repo_url", "demo_video_url", "live_url"):
        try:
            validate_web_url(getattr(project, field) or "")
        except DjangoValidationError as exc:
            raise ValidationFailed(f"{field.replace('_', ' ')}: {exc.messages[0]}") from exc


def _full_clean(project: Project) -> None:
    """Validate the instance, translating Django's exception into a portal refusal.

    `Model.full_clean()` raises `django.core.exceptions.ValidationError`, which the API's exception
    handler knows nothing about -- it would leave the view as an unhandled exception and answer
    **500**. Every field-level refusal has to arrive as a `PortalError` instead, so the API renders
    a 400 with a code and the UI renders the same message in the form.

    `full_clean` also runs `validate_constraints()`, so the one-active-project index is checked here
    in Python as well as by the database. That check and the `IntegrityError` path in
    `create_project` are the same rule seen from two sides: this one catches the ordinary case, the
    other catches the race where two requests both looked and both found nothing.
    """
    try:
        project.full_clean(exclude=["search_vector"])
    except DjangoValidationError as exc:
        if "project_one_active_per_team_per_event" in str(exc):
            raise ProjectExists(
                f"“{project.team.name}” already has a project for this event."
            ) from exc
        messages = []
        for field, errors in getattr(exc, "message_dict", {}).items():
            label = "" if field == "__all__" else f"{field.replace('_', ' ')}: "
            messages.extend(f"{label}{message}" for message in errors)
        raise ValidationFailed(" ".join(messages) or str(exc)) from exc


def _resolve_track(event: Event, track) -> Track | None:
    """Accept a Track, a primary key or None, and refuse one belonging to another event."""
    if track in (None, "", "0"):
        return None
    if isinstance(track, Track):
        resolved = track
    else:
        resolved = Track.objects.filter(pk=track).first()
        if resolved is None:
            raise ValidationFailed("That track does not exist.")
    if resolved.event_id != event.pk:
        raise ValidationFailed("That track belongs to a different event.")
    return resolved


def _apply_fields(project: Project, values: dict) -> list[str]:
    """Copy provided content fields onto the instance. Returns the names that changed."""
    changed = []
    for field in CONTENT_FIELDS:
        if field not in values:
            continue
        new = values[field]
        if field == "track":
            resolved = _resolve_track(project.event, new)
            if (resolved.pk if resolved else None) == project.track_id:
                continue
            project.track = resolved
            changed.append(field)
            continue
        new = (new or "").strip()
        if new == getattr(project, field):
            continue
        setattr(project, field, new)
        changed.append(field)
    return changed


def guard_project_create(*, actor: User, event: Event, request=None):
    """Run the create-a-project checks, in order, and resolve the caller's team.

    Returns:
        `(team, now)` -- the team the caller will create for, and the instant the guard judged
        against, to be passed straight to `create_project`.

    Split out from `create_project` so a caller that has to validate a request body can do so
    **after** these checks rather than before. The API needs exactly that: the deadline must be
    decided before the body is examined, or a late POST carrying an unknown field would be
    reported as a validation error and the participant would never learn they were late. Keeping
    the two halves here rather than inlining the guards in a view means the rule has one home.

    `create_project` runs the same guards again for its own sake -- it is a public function and
    must be safe called directly. Passing `now` through is what stops the second pass from
    reading the clock again.
    """
    now = clock.now()
    guard_submissions_open(
        event, actor=actor, action="create_project", request=request, now=now
    )

    membership = (
        TeamMember.objects.filter(event=event, user=actor).select_related("team").first()
    )
    guard_permission(
        membership is not None,
        actor=actor,
        action="create_project",
        event=event,
        request=request,
        message="You are not on a team in this event. Join or create a team first.",
    )
    return membership.team, now


def create_project(
    *,
    actor: User,
    event: Event,
    team: Team,
    request=None,
    tags=None,
    answers: dict | None = None,
    now=None,
    **fields,
) -> Project:
    """Start a project for `team`. Created as a draft, and a draft needs only a name.

    `now` lets a caller that has already read the clock and guarded (see
    `create_project_for_event`) pass its instant in rather than taking a second reading.
    """
    now = now or clock.now()
    guard_submissions_open(
        event, actor=actor, action="create_project", target=team, request=request, now=now
    )
    guard_permission(
        can_create_project(actor, team),
        actor=actor,
        action="create_project",
        event=event,
        target=team,
        request=request,
        message="Only members of the team can create its project.",
    )

    if team.event_id != event.pk:
        raise ValidationFailed("That team belongs to a different event.")

    # A courtesy check, so the refusal can name the project that already exists. The database
    # constraint below is the actual enforcement -- see this module's docstring.
    existing = Project.objects.filter(event=event, team=team, duplicate_of__isnull=True).first()
    if existing:
        raise ProjectExists(
            f"“{team.name}” already has a project for this event: “{existing.name}”. "
            "Edit that one instead of starting a second.",
            project_id=existing.pk,
        )

    name = (fields.get("name") or "").strip()
    if not name:
        raise ValidationFailed("Give your project a name. Everything else can wait.")

    project = Project(event=event, team=team, status=ProjectStatus.DRAFT, created_at=now)
    _apply_fields(project, {**fields, "name": name})
    _clean_url_fields(project)

    try:
        with transaction.atomic():
            _full_clean(project)
            project.save()
            if tags is not None:
                _write_tags(project, tags)
            if answers:
                _write_answers(project, answers)
    except IntegrityError as exc:
        # Two concurrent creates for one team: the loser lands here rather than 500ing. Only the
        # one-active-project constraint is translated; any other IntegrityError is a real bug and
        # is re-raised, because reporting it as a conflict would hide it behind a plausible
        # message.
        if "project_one_active_per_team_per_event" not in str(exc):
            raise
        raise ProjectExists(f"“{team.name}” already has a project for this event.") from exc

    search.rebuild_search_vector(project)
    audit.record(
        AuditAction.PROJECT_CREATED,
        actor=actor,
        event=event,
        target=project,
        metadata={"name": project.name, "team": team.name},
        request=request,
    )
    return project


def update_project(
    *,
    actor: User,
    project: Project,
    request=None,
    tags=_UNSET,
    answers=_UNSET,
    **fields,
) -> Project:
    """Edit a project's content. Allowed on a submitted project until the deadline.

    A submitted project must stay submittable: an edit that would empty its tagline or drop its
    track is refused, because a submitted row missing its required content would otherwise sit in
    the public gallery. Required questions added *after* submission are grandfathered -- see
    `missing_to_submit`.
    """
    now = clock.now()
    guard_submissions_open(
        project.event,
        actor=actor,
        action="update_project",
        target=project,
        request=request,
        now=now,
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="update_project",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can edit this project.",
    )

    changed = _apply_fields(project, fields)
    if "name" in changed and not project.name.strip():
        raise ValidationFailed("A project always needs a name.")
    _clean_url_fields(project)

    with transaction.atomic():
        _full_clean(project)
        if changed:
            project.save(update_fields=[*changed, "updated_at"])
        if tags is not _UNSET:
            _write_tags(project, tags)
            changed.append("tags")
        if answers is not _UNSET and answers is not None:
            _write_answers(project, answers)
            changed.append("answers")

        if project.is_submitted:
            still_missing = missing_to_submit(project, grandfather=True)
            if still_missing:
                # Raised inside the transaction on purpose: the edit must not land. This is a
                # validation refusal, not a deadline or permission one, so there is no audit row
                # to lose to the rollback.
                raise ValidationFailed(
                    "A submitted project cannot be left incomplete. Still missing: "
                    + ", ".join(still_missing)
                    + "."
                )

    if not changed:
        return project

    search.rebuild_search_vector(project)
    audit.record(
        AuditAction.PROJECT_UPDATED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"fields": sorted(set(changed))},
        request=request,
    )
    return project


def submit_project(*, actor: User, project: Project, request=None) -> Project:
    """Move a draft to submitted. A no-op for an already-submitted project."""
    now = clock.now()
    guard_submissions_open(
        project.event,
        actor=actor,
        action="submit_project",
        target=project,
        request=request,
        now=now,
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="submit_project",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can submit this project.",
    )

    if project.is_submitted:
        # Not an error, and deliberately not a re-stamp: `submitted_at` records the first
        # submission, and later edits never move it.
        return project

    missing = missing_to_submit(project)
    if missing:
        raise ValidationFailed(
            "This project is not ready to submit. Still missing: " + ", ".join(missing) + "."
        )

    project.status = ProjectStatus.SUBMITTED
    # The same instant the guard just approved, not a second reading of the clock.
    project.submitted_at = now
    with transaction.atomic():
        _full_clean(project)
        # Both columns in one write: `project_submitted_at_matches_status` refuses a submitted
        # row without a timestamp, so they can never be saved separately.
        project.save(update_fields=["status", "submitted_at", "updated_at"])

    search.rebuild_search_vector(project)
    audit.record(
        AuditAction.PROJECT_SUBMITTED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"name": project.name, "submitted_at": clock.iso(project.submitted_at)},
        request=request,
    )
    return project


