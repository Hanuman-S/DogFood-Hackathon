def missing_to_submit(project: Project, *, grandfather: bool = False) -> list[str]:
    """Labels of everything still missing before this project could be submitted.

    `Project.missing_requirements()` covers the five plain fields; the required custom questions
    need a query, which is why they are counted here.

    Args:
        grandfather: when True, a required question created *after* this project was submitted is
            not counted. An organizer who adds a required question mid-event is changing what a
            *new* submission must contain; they are not retroactively invalidating submissions
            that were complete when they were made. Without this, one organizer edit would lock
            every existing team out of its own edit form until it answered a question that did
            not exist when it submitted.
    """
    missing = list(project.missing_requirements())

    questions = CustomQuestion.objects.filter(event_id=project.event_id, required=True)
    if grandfather and project.submitted_at is not None:
        questions = questions.filter(created_at__lte=project.submitted_at)

    answered = {
        answer.question_id: (answer.value or "").strip() for answer in project.answers.all()
    }
    for question in questions.order_by("order", "id"):
        if not answered.get(question.pk):
            missing.append(f"answer to “{question.prompt}”")

    return missing


def can_submit(project: Project) -> bool:
    """Convenience for templates deciding whether to offer the submit button.

    A courtesy, never the enforcement -- `submit_project` re-checks.
    """
    return not missing_to_submit(project)


