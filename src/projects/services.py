def set_tags(*, actor: User, project: Project, tags, request=None) -> list[str]:
    """Replace a project's tags. Public write path, so it guards itself."""
    now = clock.now()
    guard_submissions_open(
        project.event, actor=actor, action="set_tags", target=project, request=request, now=now
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="set_tags",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can change its tags.",
    )

    with transaction.atomic():
        names = _write_tags(project, tags)

    search.rebuild_search_vector(project)
    audit.record(
        AuditAction.PROJECT_UPDATED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"fields": ["tags"], "tags": names},
        request=request,
    )
    return names


def _write_tags(project: Project, tags) -> list[str]:
    """Reconcile `ProjectTag` rows to exactly `tags`. No guards -- callers have run them."""
    names = parse_tags(tags)
    if len(names) > MAX_PROJECT_TAGS:
        raise ValidationFailed(f"At most {MAX_PROJECT_TAGS} tags per project (got {len(names)}).")
    for name in names:
        if len(name) > TAG_MAX_LENGTH:
            raise ValidationFailed(f"“{name[:20]}…” is too long for a tag.")

    wanted = []
    for name in names:
        tag, _ = Tag.objects.get_or_create(name=name)
        wanted.append(tag)

    project.project_tags.exclude(tag__in=wanted).delete()
    existing = set(project.project_tags.values_list("tag_id", flat=True))
    ProjectTag.objects.bulk_create(
        [ProjectTag(project=project, tag=tag) for tag in wanted if tag.pk not in existing]
    )
    return names


