def verify_image(upload) -> tuple[ContentFile, str, str]:
    """Verify an upload with Pillow and return storable bytes, format and content type.

    An upload is hostile input, so every claim it makes about itself is ignored: the extension,
    the filename and the browser's declared content type play no part. What the file *decodes to*
    is the only thing consulted.

    Returns:
        `(content, format, content_type)`, where `content` is a **re-encoded** ContentFile and not
        the bytes that were uploaded. Re-encoding is deliberate, for two reasons. It strips
        metadata, including the EXIF GPS tags a phone camera attaches, which a team demoing from
        their kitchen did not mean to publish. And it neutralises polyglots: a file that is a
        valid JPEG *and* carries an HTML or script payload after the image data passes a format
        check, but does not survive a decode-and-re-encode, because only the pixels are copied.
    """
    limit_mb = settings.MAX_UPLOAD_BYTES // (1024 * 1024)
    size = getattr(upload, "size", None)
    if size is not None and size > settings.MAX_UPLOAD_BYTES:
        raise ValidationFailed(f"Images must be {limit_mb} MB or smaller.")

    upload.seek(0)
    data = upload.read()
    if len(data) > settings.MAX_UPLOAD_BYTES:
        raise ValidationFailed(f"Images must be {limit_mb} MB or smaller.")
    if not data:
        raise ValidationFailed("That file was empty.")

    allowed = ", ".join(settings.ALLOWED_IMAGE_FORMATS)
    with warnings.catch_warnings():
        # Pillow only *warns* between MAX_IMAGE_PIXELS and twice that, and raises beyond it. A
        # warning that scrolls past in a log is not a refusal, so it is promoted to an error.
        warnings.simplefilter("error", Image.DecompressionBombWarning)
        try:
            probe = Image.open(io.BytesIO(data))
            fmt = (probe.format or "").upper()
            probe.verify()
        except (Image.DecompressionBombWarning, Image.DecompressionBombError) as exc:
            raise ValidationFailed(
                "That image decodes to too many pixels to process safely."
            ) from exc
        except Exception as exc:  # noqa: BLE001 - any decode failure is the same refusal
            raise ValidationFailed(
                f"That file is not a readable image. Upload a {allowed} file."
            ) from exc

        if fmt not in settings.ALLOWED_IMAGE_FORMATS:
            raise ValidationFailed(
                f"{fmt or 'That format'} is not accepted. Upload a {allowed} file."
            )

        # `verify()` leaves the image object unusable -- any further access raises "operation on
        # closed image". The file has to be rewound and reopened before it can be read for real.
        upload.seek(0)
        try:
            image = Image.open(io.BytesIO(data))
            image.load()
        except (Image.DecompressionBombWarning, Image.DecompressionBombError) as exc:
            raise ValidationFailed(
                "That image decodes to too many pixels to process safely."
            ) from exc
        except Exception as exc:  # noqa: BLE001
            raise ValidationFailed(
                f"That file is not a readable image. Upload a {allowed} file."
            ) from exc

    buffer = io.BytesIO()
    save_kwargs: dict = {}
    if fmt == "JPEG":
        # JPEG has no alpha channel, so a transparent source would fail to save.
        if image.mode not in ("RGB", "L"):
            image = image.convert("RGB")
        save_kwargs = {"quality": 88, "optimize": True}
    elif image.mode == "P":
        image = image.convert("RGBA")
    image.save(buffer, format=fmt, **save_kwargs)

    if buffer.tell() > settings.MAX_UPLOAD_BYTES:
        raise ValidationFailed(f"Images must be {limit_mb} MB or smaller.")

    name = f"{secrets.token_urlsafe(16)}.{FORMAT_EXTENSIONS[fmt]}"
    return ContentFile(buffer.getvalue(), name=name), fmt, FORMAT_CONTENT_TYPES[fmt]


def add_image(*, actor: User, project: Project, upload, alt_text: str = "", request=None):
    """Attach one gallery image. Public write path, so it guards itself."""
    now = clock.now()
    guard_submissions_open(
        project.event, actor=actor, action="add_image", target=project, request=request, now=now
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="add_image",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can add images.",
    )

    content, _fmt, content_type = verify_image(upload)

    with transaction.atomic():
        # The row lock is the enforcement, not a nicety. "At most N rows per parent" cannot be
        # expressed as a database constraint, so the count has to be taken and acted on with
        # nothing else inserting in between. Under READ COMMITTED two concurrent uploads would
        # otherwise both read 7 and both insert, leaving 9 images.
        locked = Project.objects.select_for_update().get(pk=project.pk)
        count = ProjectImage.objects.filter(project=locked).count()
        if count >= settings.MAX_PROJECT_IMAGES:
            raise ValidationFailed(
                f"A project can have at most {settings.MAX_PROJECT_IMAGES} images. "
                "Remove one before adding another."
            )

        image = ProjectImage(
            project=locked,
            alt_text=(alt_text or "").strip()[:200],
            order=count,
            content_type=content_type,
        )
        image.image.save(content.name, content, save=False)
        image.save()

    audit.record(
        AuditAction.PROJECT_IMAGE_ADDED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"image_id": image.pk, "content_type": content_type},
        request=request,
    )
    return image


def remove_image(*, actor: User, image, request=None) -> None:
    """Delete one gallery image, and its file once the deletion has committed."""
    project = image.project
    now = clock.now()
    guard_submissions_open(
        project.event,
        actor=actor,
        action="remove_image",
        target=project,
        request=request,
        now=now,
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="remove_image",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can remove images.",
    )

    image_id = image.pk
    with transaction.atomic():
        _delete_file_on_commit(image.image)
        image.delete()

    audit.record(
        AuditAction.PROJECT_IMAGE_REMOVED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"image_id": image_id},
        request=request,
    )


def set_thumbnail(*, actor: User, project: Project, upload, request=None) -> Project:
    """Replace the project's thumbnail. Public write path, so it guards itself.

    The thumbnail is a separate field from the gallery images and does **not** count against
    `MAX_PROJECT_IMAGES`: one card image plus a gallery of up to eight is the shape the brief
    describes.
    """
    now = clock.now()
    guard_submissions_open(
        project.event,
        actor=actor,
        action="set_thumbnail",
        target=project,
        request=request,
        now=now,
    )
    guard_permission(
        can_edit_project(actor, project),
        actor=actor,
        action="set_thumbnail",
        event=project.event,
        target=project,
        request=request,
        message="Only members of the owning team can change the thumbnail.",
    )

    content, _fmt, content_type = verify_image(upload)

    with transaction.atomic():
        if project.thumbnail:
            _delete_file_on_commit(project.thumbnail)
        project.thumbnail_content_type = content_type
        project.thumbnail.save(content.name, content, save=False)
        project.save(update_fields=["thumbnail", "thumbnail_content_type", "updated_at"])

    audit.record(
        AuditAction.PROJECT_IMAGE_ADDED,
        actor=actor,
        event=project.event,
        target=project,
        metadata={"thumbnail": True, "content_type": content_type},
        request=request,
    )
    return project


def _delete_file_on_commit(field_file) -> None:
    """Unlink a stored file only once the surrounding transaction has committed.

    Deleting inline would mean a rolled-back transaction leaves a surviving row pointing at a
    file that is gone -- a broken image for the rest of the event. Deferring inverts the failure:
    a crash between the commit and the unlink leaves an unreferenced file on the media volume.
    That is the better direction to fail in, and the residual gap is recorded in the README
    rather than papered over with a cleanup daemon nobody will run.
    """
    if not field_file:
        return
    name, storage = field_file.name, field_file.storage
    transaction.on_commit(lambda: storage.delete(name))
